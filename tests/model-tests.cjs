const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const context = { module: { exports: {} } };
vm.runInNewContext(fs.readFileSync(require('node:path').join(__dirname, '../model.js'), 'utf8'), context);
const M = context.module.exports;
const settings = { recipient: '你', birthday: '', subtitle: '祝福', letter: '信', sender: '我' };
const photo = 'data:image/png;base64,AAAA';
const old = { version: 1, settings, memories: [{ id: 's1', title: '故事', date: '', story: '', photos: [photo, photo] }] };
const next = M.migrate(old, 'gift');
assert.equal(next.photos.length, 2); assert.equal(next.stories[0].placeId, 'xian'); assert.equal(old.version, 1);
assert.equal(M.photosOf(next, 's1').length, 2);
assert.equal(M.storiesAt(next, 'jinan').length, 0);
const nested = { version: 2, settings, places: [{ id: 'jinan', name: '济南', unlocked: true, stories: old.memories }] };
assert.equal(M.migrate(nested, 'gift').stories[0].placeId, 'jinan');
assert.equal(M.migrate(nested, 'gift').unlocked[0], 'jinan');
const broken = M.copy(next); broken.photos[0].storyId = 'no-story'; assert.throws(() => M.validate(broken));
const cover = M.copy(next); cover.stories[0].coverId = 'no-photo'; assert.throws(() => M.validate(cover));
const duplicate = M.copy(next); duplicate.photos.push(duplicate.photos[0]); assert.throws(() => M.validate(duplicate));
const invalidDate = M.copy(next); invalidDate.settings.birthday = '2026-02-30'; assert.throws(() => M.validate(invalidDate));
const custom = M.copy(next); custom.places.push({ id: 'custom', name: '新地点', mode: 'train', x: 500, y: 300 }); M.validate(custom); assert.equal(M.migrate(custom).places.length, 6);
console.log('PASS model migration, ownership, foreign keys, cover validation, duplicates, date validation and extensible places');
